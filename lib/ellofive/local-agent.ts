function buildTaskPlan(prompt: string): AgentArtifact {
  const title = topicFrom(prompt);
  const steps = [
    `Clarify the goal: ${title}`,
    "List constraints (time, tools, audience).",
    "Break work into 3–7 concrete actions.",
    "Do the first action immediately (draft / generate / research).",
    "Review output, then iterate or hand off.",
  ];
  const content = [
    `# Task plan: ${title}`,
    "",
    `Request: ${prompt}`,
    "",
    ...steps.map((s, i) => `${i + 1}. ${s}`),
    "",
    "## Done when",
    `- You have a usable artifact or clear next owner for “${title}”.`,
  ].join("\n");

  return {
    type: "task_plan",
    title: `Task plan — ${title}`,
    filename: `${slugify(title)}-plan.md`,
    content,
  };
}

async function fetchLiveBrief(prompt: string): Promise<string> {
  const now = new Date().toUTCString();
  try {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), 4000);
    // Use Wikipedia "on this day" / most-read as a live-ish public feed
    const day = new Date();
    const mm = String(day.getUTCMonth() + 1).padStart(2, "0");
    const dd = String(day.getUTCDate()).padStart(2, "0");
    const res = await fetch(
      `https://en.wikipedia.org/api/rest_v1/feed/featured/${day.getUTCFullYear()}/${mm}/${dd}`,
      {
        signal: ctrl.signal,
        headers: {
          Accept: "application/json",
          "User-Agent": "NeuriyChatBase/1.0 (integration-test)",
        },
      }
    );
    clearTimeout(t);
    if (res.ok) {
      const data = (await res.json()) as {
        tfa?: { title?: string; extract?: string };
        mostread?: { articles?: Array<{ title?: string; extract?: string }> };
        news?: Array<{ links?: Array<{ title?: string }> }>;
      };
      const tfa = data.tfa;
      const top = (data.mostread?.articles || []).slice(0, 3);
      const newsTitles = (data.news || [])
        .flatMap((n) => n.links || [])
        .map((l) => l.title)
        .filter(Boolean)
        .slice(0, 5);

      const parts = [
        `Live brief · ${now}`,
        "",
        `You asked about: “${prompt.slice(0, 160)}”`,
        "",
      ];
      if (tfa?.title) {
        parts.push(
          `**Featured today:** ${tfa.title}`,
          (tfa.extract || "").slice(0, 320),
          ""
        );
      }
      if (top.length) {
        parts.push("**Trending reads:**");
        for (const a of top) {
          parts.push(
            `- ${a.title}: ${(a.extract || "").slice(0, 140)}`
          );
        }
        parts.push("");
      }
      if (newsTitles.length) {
        parts.push(
          "**In the news (Wikipedia feed):** " + newsTitles.join("; ")
        );
        parts.push("");
      }
      parts.push(
        "I can connect this to your topic, draft a summary page, or turn headlines into a task plan. Say what you want next."
      );
      return parts.join("\n");
    }
  } catch {
    /* fall through */
  }
  return (
    `Live-mode brief (${now}):\n` +
    `I couldn't reach an external live feed just now, so I'll answer from general knowledge and be explicit about uncertainty.\n` +
    `Your topic: “${prompt.slice(0, 200)}”. Ask me to refresh, or name a specific source you want me to use.`
  );
}

function chatReply(prompt: string, toolContext?: string | null): string {
  const q = prompt.trim();
  if (/what (are|is) you|who are you/i.test(q)) {
    return (
      "I'm **Neuriy AI** in ChatBase — I can chat normally, build HTML pages, draw SVG images, " +
      "plan tasks, talk about live topics, and use the Neuriy Marketplace when useful. What should we do?"
    );
  }
  if (toolContext) {
    return (
      `Here's what I put together for you.\n\n` +
      `You asked: “${q.slice(0, 240)}”\n\n` +
      `I used Marketplace context where relevant and answered in plain language. ` +
      `Ask me to refine, expand, or turn this into a page/image/task plan.`
    );
  }
  return (
    `Got it — “${q.slice(0, 280)}”\n\n` +
    `Here's a direct Neuriy take: I can help with conversation, code, HTML pages, SVG illustrations, ` +
    `task plans, and Marketplace lookups. Tell me the outcome you want and I'll produce it (not just describe it).`
  );
}

function slugify(s: string): string {
  return (
    String(s)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 48) || "neuriy"
  );
}

export async function runLocalAgent(opts: {
  prompt: string;
  model?: string;
  toolContext?: string | null;
  marketplaceUnavailable?: boolean;
  ellofiveUnavailable?: boolean;
  toolData?: unknown;
}): Promise<AgentResult> {
  const intent = detectIntent(opts.prompt);
  const artifacts: AgentArtifact[] = [];
  let reply = "";

  switch (intent) {
    case "greet":
      reply =
        "Hi — I'm Neuriy. Talk normally, or ask me to make an HTML page, draw an SVG image, plan a task, or check live topics.";
      break;
    case "html": {
      const art = buildHtmlPage(opts.prompt);
      artifacts.push(art);
      reply =
        `I built an HTML page for you: **${art.title}**.\n\n` +
        `Open the artifact below (or save \`${art.filename}\`). Want a different style, more sections, or a matching SVG hero?`;
      break;
    }
    case "image": {
      const art = buildSvgImage(opts.prompt);
      artifacts.push(art);
      reply =
        `I generated an SVG illustration: **${art.title}**.\n\n` +
        `You can download \`${art.filename}\` or ask me to tweak colors, layout, or text.`;
      break;
    }
    case "task": {
      const art = buildTaskPlan(opts.prompt);
      artifacts.push(art);
      reply =
        `I drafted a concrete task plan for **${topicFrom(opts.prompt)}** and started structuring the work.\n\n` +
        `Say “do step 1” and I'll execute the next action (page, image, code, or Marketplace lookup).`;
      break;
    }
    case "live": {
      const brief = await fetchLiveBrief(opts.prompt);
      reply = brief;
      artifacts.push({
        type: "markdown",
        title: "Live brief",
        filename: "live-brief.md",
        content: brief,
      });
      break;
    }
    case "code":
      reply =
        `Here's a practical code-oriented reply for: “${opts.prompt.slice(0, 160)}”\n\n` +
        "```typescript\n" +
        "export function handleRequest(input: string): string {\n" +
        "  const trimmed = input.trim();\n" +
        "  if (!trimmed) throw new Error('empty');\n" +
        "  return `Neuriy processed: ${trimmed.slice(0, 120)}`;\n" +
        "}\n" +
        "```\n\n" +
        "Want this as a Next.js route, a full HTML demo, or tests next?";
      break;
    case "marketplace":
      reply = formatMarketplaceAnswer(opts.prompt, opts.toolData, opts.toolContext);
      break;
    default:
      reply = chatReply(opts.prompt, opts.toolContext);
  }

  if (opts.marketplaceUnavailable) {
    reply =
      "Marketplace temporarily unavailable.\n\n" +
      "The AI can still answer using its available knowledge, but Marketplace data could not be retrieved for this request.\n\n" +
      reply;
  }

  if (opts.model === "reasoning" || opts.model === "code") {
    reply = `_(mode: ${opts.model})_\n\n` + reply;
  }

  return {
    reply,
    artifacts,
    intent,
    provider: "neuriy-local-agent",
  };
}

function formatMarketplaceAnswer(
  prompt: string,
  toolData: unknown,
  toolContext?: string | null
): string {
  const apps = Array.isArray(toolData) ? toolData : [];
  if (apps.length) {
    const lines = apps.slice(0, 8).map((a: Record<string, unknown>, i: number) => {
      const title = String(a.title || a.name || a.id || "App");
      const summary = String(a.summary || a.description || "").slice(0, 140);
      const category = String(a.category || "");
      return `${i + 1}. **${title}**${category ? ` · ${category}` : ""}${summary ? ` — ${summary}` : ""} (from Marketplace: ${title})`;
    });
    return (
      `I searched the Neuriy Marketplace for “${prompt.slice(0, 120)}” and found these matches:\n\n` +
      lines.join("\n") +
      `\n\nWant details on one of them, or should I open the best match?`
    );
  }
  if (toolContext) {
    return (
      `I queried the Marketplace for “${prompt.slice(0, 120)}”.\n\n` +
      `No strong app matches came back. Try a broader category (Assistants, Developer Tools, Creative) or another keyword.`
    );
  }
  return "I can search the Neuriy Marketplace for apps. Tell me what you need (e.g. coding assistant, creative tools).";
}

/** Embed artifacts into the chat reply so the UI shows them without extra infra. */
export function formatArtifactsForChat(artifacts: AgentArtifact[]): string {
  if (!artifacts.length) return "";
  const parts: string[] = ["", "---", "**Artifacts**"];
  for (const a of artifacts) {
    parts.push(`### ${a.title}`);
    if (a.type === "svg") {
      parts.push("```svg");
      parts.push(a.content);
      parts.push("```");
    } else if (a.type === "html") {
      parts.push("```html");
      parts.push(a.content);
      parts.push("```");
    } else {
      parts.push("```markdown");
      parts.push(a.content);
      parts.push("```");
    }
    if (a.filename) parts.push(`_File: \`${a.filename}\`_`);
  }
  return parts.join("\n");
}
