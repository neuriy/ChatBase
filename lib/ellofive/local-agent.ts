/**
 * Local Neuriy agent — capable chat when ElloFive is unreachable.
 * Handles: normal talk, HTML pages, SVG images, multi-step tasks, live topics.
 * Inspired by FRC7 packages/neuriy localGenerate, extended for ChatBase UX.
 */

export type AgentArtifact = {
  type: "html" | "svg" | "markdown" | "task_plan";
  title: string;
  content: string;
  filename?: string;
};

export type AgentResult = {
  reply: string;
  artifacts: AgentArtifact[];
  intent: string;
  provider: "neuriy-local-agent";
};

type Intent =
  | "greet"
  | "html"
  | "image"
  | "task"
  | "live"
  | "code"
  | "marketplace"
  | "chat";

export function detectIntent(text: string): Intent {
  const t = text.toLowerCase();
  if (/^(hi|hello|hey|hoi|hallo|bonjour|salut)\b[.!?\s]*$/i.test(t.trim())) {
    return "greet";
  }
  if (
    /\b(html\s*page|web\s*page|landing\s*page|make\s+(a\s+)?(page|website|site)|create\s+(a\s+)?(page|website|html)|build\s+(a\s+)?(page|website))\b/i.test(
      t
    )
  ) {
    return "html";
  }
  if (
    /\b(image|img|picture|illustration|svg|draw|logo|icon|generate\s+(an?\s+)?(image|picture|drawing))\b/i.test(
      t
    )
  ) {
    return "image";
  }
  if (
    /\b(live|news|today|current|right\s+now|happening|weather|stock|crypto|breaking)\b/i.test(
      t
    )
  ) {
    return "live";
  }
  if (
    /\b(task|todo|plan|steps|how\s+do\s+i|help\s+me\s+(do|build|setup|fix)|checklist)\b/i.test(
      t
    )
  ) {
    return "task";
  }
  if (
    /\b(code|function|typescript|javascript|python|bug|refactor|api\s+route)\b/i.test(
      t
    )
  ) {
    return "code";
  }
  if (/\b(marketplace|neuriy\s+apps?|find\s+app|catalog)\b/i.test(t)) {
    return "marketplace";
  }
  return "chat";
}

function topicFrom(prompt: string): string {
  const cleaned = prompt
    .replace(
      /\b(please|can you|could you|make|create|generate|build|draw|write|me|an?|the|a)\b/gi,
      " "
    )
    .replace(/\s+/g, " ")
    .trim();
  return cleaned.slice(0, 80) || "Neuriy";
}

function escapeHtml(s: string): string {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

